supplier_map AS (
    SELECT
        supplier_id,
        supplier_name,
        supplier_contact,
        supplier_email,
        supplier_phone,
        supplier_address,
        supplier_city,
        supplier_country
    FROM clickhouse.dwh.dim_supplier
