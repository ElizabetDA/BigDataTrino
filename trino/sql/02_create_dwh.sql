SELECT
    TRY_CAST(s.id AS bigint) AS fact_id,
    TRY_CAST(s.id AS bigint) AS order_id,
    CAST(date_format(TRY(CAST(date_parse(s.sale_date, '%c/%e/%Y') AS date)), '%Y%m%d') AS bigint) AS date_id,
    TRY_CAST(s.sale_customer_id AS bigint) AS customer_id,
    TRY_CAST(s.sale_product_id AS bigint) AS product_id,
    sm.store_id AS store_id,
    sup.supplier_id AS supplier_id,
    TRY_CAST(s.sale_seller_id AS bigint) AS seller_id,
    NULLIF(TRIM(s.seller_first_name), '') AS seller_first_name,
    NULLIF(TRIM(s.seller_last_name), '') AS seller_last_name,
    NULLIF(TRIM(s.seller_email), '') AS seller_email,
    NULLIF(TRIM(s.seller_country), '') AS seller_country,
    TRY_CAST(s.sale_quantity AS integer) AS sale_quantity,
    TRY_CAST(s.product_price AS double) AS unit_price,
    TRY_CAST(s.sale_total_price AS double) AS sale_total_price
FROM unified_source s
LEFT JOIN store_map sm
    ON COALESCE(NULLIF(TRIM(s.store_name), ''), '') = COALESCE(sm.store_name, '')
   AND COALESCE(NULLIF(TRIM(s.store_email), ''), '') = COALESCE(sm.store_email, '')
   AND COALESCE(NULLIF(TRIM(s.store_phone), ''), '') = COALESCE(sm.store_phone, '')
LEFT JOIN supplier_map sup
    ON COALESCE(NULLIF(TRIM(s.supplier_name), ''), '') = COALESCE(sup.supplier_name, '')
   AND COALESCE(NULLIF(TRIM(s.supplier_email), ''), '') = COALESCE(sup.supplier_email, '')
   AND COALESCE(NULLIF(TRIM(s.supplier_phone), ''), '') = COALESCE(sup.supplier_phone, '')
WHERE TRY_CAST(s.id AS bigint) IS NOT NULL;
